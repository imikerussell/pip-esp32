#!/usr/bin/env python3
"""Generate firmware/main/secrets.h (git-ignored) from .env. Never hand-copy secrets.

Only what the device needs: Wi-Fi, the bridge URL and the shared X-Pet-Key secret. No API keys.
Run from the project root:  python3 scripts/gen_secrets.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
env = {}
for raw in (ROOT / ".env").read_text().splitlines():
    line = raw.strip()
    if line and not line.startswith("#") and "=" in line:
        k, v = line.split("=", 1)
        env[k.strip()] = v.strip().strip('"').strip("'")

need = ["WIFI_SSID", "WIFI_PASSWORD", "BRIDGE_HOST", "BRIDGE_PORT", "BRIDGE_SHARED_SECRET"]
missing = [k for k in need if not env.get(k)]
if missing:
    raise SystemExit(f"empty in .env: {', '.join(missing)}")


def c(s: str) -> str:
    return json.dumps(s)  # valid C string literal for ASCII/UTF-8 text


out = ROOT / "firmware" / "main" / "secrets.h"
out.write_text(
    "// GENERATED by scripts/gen_secrets.py from .env. Do not edit, do not commit.\n"
    "#pragma once\n"
    f"#define PET_WIFI_SSID {c(env['WIFI_SSID'])}\n"
    f"#define PET_WIFI_PASS {c(env['WIFI_PASSWORD'])}\n"
    f"#define PET_BRIDGE_URL {c('http://' + env['BRIDGE_HOST'] + ':' + env['BRIDGE_PORT'] + '/react')}\n"
    f"#define PET_KEY {c(env['BRIDGE_SHARED_SECRET'])}\n"
    f"#define PET_LOOK_SECONDS {int(env.get('CAMERA_LOOK_SECONDS', '8') or 8)}\n"
)
out.chmod(0o600)
print(f"wrote {out.relative_to(ROOT)} (ssid set, bridge http://{env['BRIDGE_HOST']}:{env['BRIDGE_PORT']}/react)")
